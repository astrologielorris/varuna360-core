"""Catalog files on disk and the committed English source (SPEC-LOC-002 §3.2). Qt-free.

  en/ui/<area>.json      GENERATED by tools/i18n_extract.py: key -> English value
                         (or a wrapper {"text": <value>, "tight": true, "selector": "ordinal"}).
  en/terms/<kind>.json   GENERATED: ident -> {"name": ..., "abbr": ...}.
  <code>/ui/<area>.json  key -> {"text": <value>, "src": <hash>, "ok": <hash|null>}.
  <code>/terms/<kind>.json  ident -> {"name": ..., <forms>, "gender": ...,
                         "policy": ..., "src": <hash>, "ok": <hash|null>}.
"""
from __future__ import annotations

import json
import os
from pathlib import Path
from typing import Any, Dict, List, Set, Tuple
from zlib import crc32 as _crc32

from core.i18n.languages import ENGLISH
from core.i18n.templates import (
    is_plural, source_hash, template_fields, unwrap_english, value_fields, variants)


def _read_folder(folder: Path, problems: List[str]) -> Dict[str, Any]:
    """Merge every *.json of a folder (sorted by name); a key in two files is reported."""
    merged: Dict[str, Any] = {}
    names = sorted(n for n in os.listdir(folder) if n.endswith(".json")) if folder.is_dir() else []
    for path in (folder / n for n in names):
        try:
            data = json.loads(path.read_bytes())
        except (OSError, ValueError) as exc:
            problems.append(f"{path.name}: unreadable ({exc})")
            continue
        if not isinstance(data, dict):
            problems.append(f"{path.name}: not an object")
            continue
        if not merged.keys().isdisjoint(data):
            problems += [f"{path.name}: duplicate key {k!r}" for k in merged.keys() & data.keys()]
        merged.update(data)
    return merged


def _read_terms(folder: Path, problems: List[str]) -> Dict[str, Dict[str, dict]]:
    out: Dict[str, Dict[str, dict]] = {}
    if not folder.is_dir():
        return out
    for path in sorted(folder.glob("*.json")):
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            problems.append(f"terms/{path.name}: unreadable ({exc})")
            continue
        if not isinstance(data, dict):
            problems.append(f"terms/{path.name}: not an object")
            continue
        kind = path.stem
        table: Dict[str, dict] = {}
        for ident, entry in data.items():
            if isinstance(entry, dict) and isinstance(entry.get("name"), str) and entry["name"]:
                table[str(ident)] = entry
            else:
                problems.append(f"terms/{path.name}: bad entry {ident!r}")
        out[kind] = table
    return out


class EnglishSource:
    """The committed English catalog: values, metadata and hashes."""

    def __init__(self, root: Path):
        self.problems: List[str] = []
        raw = _read_folder(root / ENGLISH / "ui", self.problems)
        self.values: Dict[str, Any] = raw          # plain values as read
        self.meta: Dict[str, Dict[str, Any]] = {}
        for key in [k for k, v in raw.items() if type(v) is dict and "text" in v]:
            value, meta = unwrap_english(raw[key])
            self.meta[key] = meta
            raw[key] = value
        self.hashes = _LazyHashes(self.values)
        self._fields: Dict[str, Set[str]] = {}
        self._call_params: Dict[str, Tuple[frozenset, frozenset]] = {}
        self.terms = _read_terms(root / ENGLISH / "terms", self.problems)

    def selector(self, key: str) -> str:
        return self.meta.get(key, {}).get("selector", "count")

    def call_params(self, key: str) -> Tuple[frozenset, frozenset]:
        """(offered, required) params of a key's call, for per-variant validation.

        offered: every param the call passes (English fields, plus the plural
        selector; a declared param set for format.date.*). required: every param
        an English template prints, minus the plural selector (CLDR practice: a
        'one' variant may say "un an") and minus a select param no English
        template prints. A declared param set requires nothing (INV-5 exception:
        a date pattern orders and pads its own way)."""
        got = self._call_params.get(key)
        if got is None:
            value = self.values[key]
            declared = self.meta.get(key, {}).get("params")
            if declared:
                got = (frozenset(declared), frozenset())
            elif type(value) is str:
                got = (frozenset(self.fields(key)),) * 2
            else:
                got = self._value_params(key, value)
            self._call_params[key] = got
        return got

    def _value_params(self, key: str, value: Any) -> Tuple[frozenset, frozenset]:
        """call_params of a plural or select English value."""
        offered = set(self.fields(key))
        required: Set[str] = set()
        for v in variants(value):
            required |= template_fields(v)
        if is_plural(value):
            sel = self.selector(key)
            offered.add(sel)
            required.discard(sel)
        return frozenset(offered), frozenset(required)

    def fields(self, key: str) -> Set[str]:
        """Placeholder names of the English value (memoized; TemplateError if invalid)."""
        got = self._fields.get(key)
        if got is None:
            got = self._fields[key] = value_fields(self.values[key])
        return got


def _hash_of(value: Any) -> str:
    return "%08x" % _crc32(value.encode("utf-8")) if type(value) is str else source_hash(value)


class _LazyHashes(dict):
    """key -> source_hash(English value), computed on first access."""

    def __init__(self, values: Dict[str, Any]):
        super().__init__()
        self._values = values

    def __missing__(self, key):
        h = self[key] = _hash_of(self._values[key])
        return h

    def __contains__(self, key):
        return key in self._values

    def get(self, key, default=None):
        return self[key] if key in self._values else default

    def complete(self) -> "_LazyHashes":
        """Hash every English value now (one comprehension: the public-build load)."""
        if len(self) != len(self._values):
            self.update({k: ("%08x" % _crc32(v.encode("utf-8")) if type(v) is str
                             else source_hash(v))
                         for k, v in self._values.items() if not dict.__contains__(self, k)})
        return self
